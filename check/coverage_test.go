// The test executable doubles as a deterministic native-tool process, including on Windows.
func TestMain(m *testing.M) {
	if os.Getenv("GRC_HELPER") == "1" {
		name := strings.TrimSuffix(filepath.Base(os.Args[0]), ".exe")
		if name == "wc" {
			if _, err := os.Stat(os.Args[len(os.Args)-1]); err != nil {
				os.Exit(2)
			}
			fmt.Println(os.Getenv("GRC_LINES"))
			os.Exit(0)
		}
		fmt.Print(os.Getenv("GRC_OUTPUT"))
		fmt.Fprint(os.Stderr, os.Getenv("GRC_STDERR"))
		code, _ := strconv.Atoi(os.Getenv("GRC_EXIT"))
		os.Exit(code)
	}
	os.Exit(m.Run())
}
func helperTools(t *testing.T) string {
	t.Helper()
	exe, err := os.Executable()
	if err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(exe)
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	for _, name := range []string{"go", "gofmt", "gocyclo", "misspell", "ineffassign", "wc"} {
		if runtime.GOOS == "windows" {
			name += ".exe"
		}
		if err = os.WriteFile(filepath.Join(dir, name), b, 0700); err != nil {
			t.Fatal(err)
		}
	}
	t.Setenv("PATH", dir+string(os.PathListSeparator)+os.Getenv("PATH"))
	t.Setenv("GRC_HELPER", "1")
	t.Setenv("GRC_LINES", "5")
	return exe
}
func putFile(t *testing.T, p, s string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(p), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(s), 0600); err != nil {
		t.Fatal(err)
	}
}
func TestFileLifecycle(t *testing.T) {
	root := t.TempDir()
	a := filepath.Join(root, "a.go")
	putFile(t, a, "package a\n")
	missing := filepath.Join(root, "missing")
	if err := RenameFiles([]string{missing, a}); err == nil {
		t.Fatal("missing source accepted")
	}
	if _, err := os.Stat(a + ".grc.bk"); err != nil {
		t.Fatal(err)
	}
	if err := RevertFiles([]string{missing, a}); err == nil {
		t.Fatal("missing backup accepted")
	}
	if _, err := os.Stat(a); err != nil {
		t.Fatal(err)
	}
	for _, line := range []string{"// Code generated automatically", "/* autogenerated", "//@generated", "/*auto-generated"} {
		putFile(t, a, line+"\npackage a\n")
		if !autoGenerated(a) {
			t.Fatal(line)
		}
	}
	if autoGenerated(missing) {
		t.Fatal("missing file considered generated")
	}
	putFile(t, a, "// Code generated automatically\n")
	putFile(t, filepath.Join(root, "normal.go"), "package a\n")
	files, skipped, err := GoFiles(root)
	if err != nil || len(files) != 1 || len(skipped) != 1 {
		t.Fatalf("%v %v %v", files, skipped, err)
	}
	GoFiles(missing)
}
